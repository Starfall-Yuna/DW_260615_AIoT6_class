-- SELECT문 :: 테이블 데이터 조회

-- 계정 테이블 생성 (4개의 칼럼)
CREATE TABLE ACCOUNT(
    ID VARCHAR2(30),
    PASSWD VARCHAR2(30),
    ORNER_NAME VARCHAR2(50),
    CREATE_DATE DATE
);

INSERT INTO ACCOUNT VALUES ('leeyn', '1234', 'Lee', '2026-07-01');
