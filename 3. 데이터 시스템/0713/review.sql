-- 영화 좌석 예매 테이블(RESERVATION) 테이블 구성 (CREATE)
CREATE TABLE RESERVATION(
    RESERV_ID NUMBER,
    NAME VARCHAR2(50),
    TITLE VARCHAR2(100),
    SEAT_NUM NUMBER,
    PRICE NUMBER
);
-- 칼럼 추가 (ALTER, ADD)
--      => ADD, DROP COLUMN, RENAME COLUMN(칼럼 이름 수정), MODIFY(데이터 타입 수정)
ALTER TABLE RESERVATION ADD RESERV_DATE DATE;
-- 칼럼 데이터 타입 수정(ALTER, MODIFY)
ALTER TABLE RESERVATION MODIFY RESERV_ID VARCHAR2(10);

SELECT * FROM RESERVATION;

-- 예시 데이터(3개) 넣기 (INSERT)
INSERT INTO RESERVATION VALUES ('1', 'Lee', '눈동자', 5, 15000, '2026-07-13');
INSERT INTO RESERVATION VALUES ('2', 'Park', '모아나', 15, 10000, '2026-08-30');
INSERT INTO RESERVATION VALUES ('3', 'Jung', '토이 스토리', 25, 9000, '2026-07-30');

-- 데이터 전체/일부 수정 (UPDATE)
--      NAME 칼럼값이 'Jung'인 데이터에 한하여, NAME 칼럼값을 'Jang'으로 수정
UPDATE RESERVATION SET NAME='Jang' WHERE NAME='Jung';
--      전체 데이터에 있어, 기존의 각 PRICE 칼럼값에 500을 더한 값으로 수정
UPDATE RESERVATION SET PRICE = PRICE+500;

-- 데이터 전체/일부 삭제 (DELETE)
-- DELETE FROM RESERVATION;        -- 전체 삭제
DELETE FROM RESERVATION WHERE PRICE<10000;

-- 테이블의 데이터만 삭제 & 테이블 전체 삭제
TRUNCATE TABLE RESERVATION;
DROP TABLE RESERVATION;

