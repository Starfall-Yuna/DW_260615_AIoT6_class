-- DDL(Definition) :: 데이터 정의어, 데이터 구조 정의 명령어
--    CREATE, ALTER, DROP, TRUNCATE
-- DML(Manipulation) :: 데이터 조작어, 데이터 구조 내부 조작 명령어
--    INSERT, UPDATE, DELETE
-- DQL(Query) :: SELECT(검색)

CREATE TABLE NUM_TABLE(   -- NUM_TABLE 이름의 테이블(표) 생성 (2개의 칼럼)
    TMP1 NUMBER,
    TMP2 NUMBER
);  
INSERT INTO NUM_TABLE VALUES (100, 3);
  -- NUM_TABLE에 (TMP1=100, TMP2=3) 데이터를 삽입

ALTER TABLE NUM_TABLE ADD ADD_RESULT NUMBER;
  -- "TMP1+TMP2" 이름의 칼럼을 NUMBER 타입으로 추가
  --    ADD, DROP COLUMN, MODIFY, RENAME COLUMN
UPDATE NUM_TABLE SET ADD_RESULT = TMP1+TMP2;
  -- "TMP1+TMP2" 칼럼에 두 숫자의 합 저장하면서 데이터 수정(UPDATE)

-- 1) ADD_RESULT에 이어, 뺄셈/곱셈/나눗셈/몫/나머지 결과를 저장하는 칼럼 추가(ADD)
ALTER TABLE NUM_TABLE ADD SUB_RESULT NUMBER;
ALTER TABLE NUM_TABLE ADD MUL_RESULT NUMBER;
ALTER TABLE NUM_TABLE ADD DIV_RESULT NUMBER;
ALTER TABLE NUM_TABLE ADD TRUNC_RESULT NUMBER;  -- TRUNC() :: 소수점 아래를 버리는 함수
--    100 / 3 = 33.333333...  -> 33 (몫)
ALTER TABLE NUM_TABLE ADD MOD_RESULT NUMBER;

-- 2) 새로 추가된 칼럼에, TMP1과 TMP2에 대한 사칙연산 결과를 적절히 삽입
UPDATE NUM_TABLE SET SUB_RESULT = TMP1-TMP2;
UPDATE NUM_TABLE SET MUL_RESULT = TMP1*TMP2;
UPDATE NUM_TABLE SET DIV_RESULT = TMP1/TMP2;
UPDATE NUM_TABLE SET TRUNC_RESULT = TRUNC(TMP1/TMP2);
UPDATE NUM_TABLE SET MOD_RESULT = MOD(TMP1, TMP2);

SELECT * FROM NUM_TABLE;
  -- NUM_TABLE의 전체 데이터 조회